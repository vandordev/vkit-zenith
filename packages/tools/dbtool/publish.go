package dbtool

import (
	"context"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"syscall"
	"time"
)

const generatedNotice = "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.29.0"

func checkAncestors(path string) error {
	for p := path; ; p = filepath.Dir(p) {
		info, err := os.Lstat(p)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if err == nil && info.Mode()&os.ModeSymlink != 0 {
			return errors.New("generated output: symlink path refused")
		}
		if p == filepath.Dir(p) {
			return nil
		}
	}
}

func ownedTree(root string) error {
	return filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return errors.New("generated output: symlink refused")
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		if rel == "README.md" && entry.Type().IsRegular() {
			return nil
		}
		if !entry.Type().IsRegular() || !strings.HasSuffix(path, ".go") {
			return errors.New("generated output: unowned file refused")
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(content), generatedNotice+"\n") {
			return errors.New("generated output: handwritten file refused")
		}
		return nil
	})
}

// publish serializes generation and swaps a complete same-filesystem staged tree.
// A backup is restored on rename failure; an interrupted backup is never deleted.
func publish(ctx context.Context, output string, generate func(context.Context, string) error) (err error) {
	output, err = filepath.Abs(output)
	if err != nil {
		return err
	}
	if err := checkAncestors(output); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	lockPath := output + ".lock"
	if err := checkAncestors(lockPath); err != nil {
		return err
	}
	fd, err := syscall.Open(lockPath, syscall.O_CREAT|syscall.O_RDWR|syscall.O_NOFOLLOW, 0600)
	if err != nil {
		return errors.New("generated output: cannot open publication lock")
	}
	defer syscall.Close(fd)
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		err = syscall.Flock(fd, syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			break
		}
		if err != syscall.EWOULDBLOCK {
			return errors.New("generated output: publication lock failed")
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(25 * time.Millisecond):
		}
	}
	defer syscall.Flock(fd, syscall.LOCK_UN)
	if err := checkAncestors(output); err != nil {
		return err
	}
	backup := output + ".backup"
	if _, err := os.Lstat(backup); !os.IsNotExist(err) {
		return errors.New("generated output: existing recovery backup requires operator inspection")
	}
	exists := true
	if _, err := os.Lstat(output); os.IsNotExist(err) {
		exists = false
	} else if err != nil {
		return err
	}
	if exists {
		if err := ownedTree(output); err != nil {
			return err
		}
	}
	stage, err := os.MkdirTemp(filepath.Dir(output), ".dbgen-stage-")
	if err != nil {
		return err
	}
	defer func() {
		if e := os.RemoveAll(stage); e != nil {
			err = errors.Join(err, errors.New("generated output: staging cleanup failed"))
		}
	}()
	if exists {
		if readme, e := os.ReadFile(filepath.Join(output, "README.md")); e == nil {
			if err := os.WriteFile(filepath.Join(stage, "README.md"), readme, 0644); err != nil {
				return err
			}
		} else if !os.IsNotExist(e) {
			return e
		}
	}
	if err := generate(ctx, stage); err != nil {
		return err
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if err := ownedTree(stage); err != nil {
		return err
	}
	if exists {
		if err := ownedTree(output); err != nil {
			return err
		}
		if err := os.Rename(output, backup); err != nil {
			return errors.New("generated output: backup failed")
		}
	}
	if err := os.Rename(stage, output); err != nil {
		if exists {
			if restore := os.Rename(backup, output); restore != nil {
				return errors.New("generated output: publication and restore failed; inspect recovery backup")
			}
		}
		return errors.New("generated output: publication failed; previous tree restored")
	}
	if exists {
		if err := os.RemoveAll(backup); err != nil {
			return errors.New("generated output: published but backup cleanup failed")
		}
	}
	return nil
}
