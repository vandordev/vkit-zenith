package handlergen

import (
	"bytes"
	"fmt"
	"go/format"
)

const notice = "// Code generated by zenith handler-gen. DO NOT EDIT."

func render(module string, constructors []constructor) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "%s\n\npackage main\n\nimport (\n\"go.uber.org/fx\"\nserver %q\n", notice, module+"/internal/server")
	aliases := make(map[string]string)
	for _, c := range constructors {
		if _, exists := aliases[c.Import]; !exists {
			alias := fmt.Sprintf("handler%d", len(aliases))
			aliases[c.Import] = alias
			fmt.Fprintf(&out, "%s %q\n", alias, c.Import)
		}
	}
	fmt.Fprintln(&out, ")\n\nfunc handlerOptions() fx.Option { return fx.Invoke(")
	for _, c := range constructors {
		fmt.Fprintf(&out, "%s.%s,\n", aliases[c.Import], c.Name)
	}
	fmt.Fprintln(&out, ") }\n\nfunc newApp() *fx.App { return fx.New(server.Module, handlerOptions()) }")
	return format.Source(out.Bytes())
}
